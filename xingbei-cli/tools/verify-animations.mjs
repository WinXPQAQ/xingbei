// Real animation timing, lifecycle and responsive evidence; no disabled motion.
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const base = process.env.CURRENT_URL || "http://127.0.0.1:4173";
const output = resolve(process.argv[2] || "xingbei-cli/artifacts/frontend/restoration/2026-10-10/animation-review");
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const checks = [], issues = [], traces = [];
function check(label, value) { assert.ok(value, label); checks.push(label); }
try {
  for (const viewport of [{ width: 1440, height: 900 }, { width: 1280, height: 720 }, { width: 844, height: 390 }, { width: 390, height: 844 }]) {
    const tag = `${viewport.width}x${viewport.height}`;
    const context = await browser.newContext({ viewport, hasTouch: viewport.width < 900, recordVideo: { dir: output }, reducedMotion: "no-preference" });
    const page = await context.newPage(); page.setDefaultTimeout(30000);
    page.on("pageerror", error => issues.push({ tag, message: error.message }));
    page.on("console", message => { if (message.type() === "error") issues.push({ tag, message: message.text() }); });
    page.on("response", response => { if (response.status() >= 400) issues.push({ tag, url: response.url(), status: response.status() }); });
    const state = () => page.evaluate(() => window.xingbeiDev.exportState());
    const animation = () => page.evaluate(() => window.xingbeiDev.animations());
    const settled = async () => {
      await page.waitForFunction(() => !window.xingbeiDev.animations().playing && window.xingbeiDev.animations().active === 0);
      await page.evaluate(async () => Promise.all(document.getAnimations().map(animation => animation.finished.catch(() => {}))));
    };
    const scene = async name => { await page.goto(`${base}/web/dev.html?scene=${name}`); await page.waitForFunction(() => !!window.xingbeiDev); await settled(); };
    await page.goto(`${base}/`);
    await page.waitForFunction(() => document.querySelector("#hand .card") && !document.querySelector("#hand .card").disabled);
    check(`${tag}: 正式页面真实开局动画后六人各4牌`, await page.locator(".player .count").allTextContents().then(counts => counts.length === 6 && counts.every(text => text === "4/6")));
    check(`${tag}: 正式页面摸牌到位且清理`, await page.locator("#hand .card").count() === 4 && await page.locator(".animation-card").count() === 0);
    check(`${tag}: 正式页面不暴露开发接口`, await page.evaluate(() => !window.xingbeiDev));
    await scene("opening");
    await page.evaluate(() => { window.originalHand = document.querySelector("#hand .card"); window.originalPlayer = document.querySelector('.player[data-player="0"]'); });
    await page.locator("#hand .card").first().click();
    check(`${tag}: 保留手牌和玩家节点`, await page.evaluate(() => window.originalHand === document.querySelector("#hand .card") && window.originalPlayer === document.querySelector('.player[data-player="0"]')));
    const selected = (await state()).game.players[0].hand[0];
    await page.getByRole("button", { name: "取消", exact: true }).click();
    check(`${tag}: 取消不产生出牌动画`, !(await animation()).trace.some(event => event.type === "move"));
    await page.locator("#hand .card").first().click();
    await page.locator('.player.targetable[data-player="1"]').click();
    await page.waitForFunction(() => window.xingbeiDev.animations().active > 0);
    check(`${tag}: 出牌运行时锁定操作`, await page.locator("#hand .card").first().isDisabled());
    const flying = await page.locator(".animation-card").first().boundingBox();
    check(`${tag}: 动画牌位于可视窗口`, flying && flying.x > -120 && flying.y > -120 && flying.x < viewport.width && flying.y < viewport.height);
    await page.screenshot({ path: resolve(output, `card-flight-${tag}.png`) });
    await page.waitForFunction(() => window.xingbeiDev.exportState().current === 1); await settled();
    check(`${tag}: 状态牌实际挂载且动画清理`, (await state()).game.players[1].statuses.some(card => card.id === selected.id) && await page.locator(".animation-card").count() === 0);
    traces.push({ tag, scene: "status-play", trace: (await animation()).trace });
    await scene("purchase"); await page.locator("#buy").click();
    await page.waitForFunction(() => window.xingbeiDev.animations().trace.some(event => event.type === "draw" && event.status === "started"));
    const incoming = await page.locator(".animation-card").all();
    check(`${tag}: 摸牌按批次播放`, incoming.length === 3);
    await page.screenshot({ path: resolve(output, `draw-${tag}.png`) });
    await page.waitForFunction(() => window.xingbeiDev.exportState().current === 1); await settled();
    const drawTrace = (await animation()).trace;
    check(`${tag}: 摸牌保留原版800毫秒节奏`, drawTrace.find(event => event.type === "draw" && event.status === "finished").at - drawTrace.find(event => event.type === "draw" && event.status === "started").at >= 700);
    check(`${tag}: 资源变化接入真实事件`, drawTrace.some(event => event.type === "stones"));
    await scene("opponent-draw"); await page.locator("#dev-step").click();
    await page.waitForFunction(() => window.xingbeiDev.animations().trace.some(event => event.type === "draw" && event.status === "started"));
    check(`${tag}: 对手摸牌只显示牌背`, await page.locator(".animation-card.card-back").count() === 3 && await page.locator(".animation-card .image").count() === 0);
    await page.waitForFunction(() => window.xingbeiDev.exportState().current === 2); await settled();
    await scene("poison-stack");
    check(`${tag}: 中毒逐张播放`, (await animation()).trace.filter(event => event.type === "effect" && event.status === "started").length === 2 && (await state()).game.players[0].hand.length === 6);
    traces.push({ tag, scene: "poison-stack", trace: (await animation()).trace });
    await scene("shield-hit"); await page.locator("#dev-step").click();
    await page.waitForFunction(() => window.xingbeiDev.exportState().pendingChoice?.type === "hand");
    await page.getByRole("button", { name: "不响应", exact: true }).click();
    await page.waitForFunction(() => window.xingbeiDev.exportState().current === 2); await settled();
    const shield = (await animation()).trace;
    check(`${tag}: 圣盾显示未命中且没有伤害动画`, shield.some(event => event.type === "miss") && !shield.some(event => event.type === "damage"));
    await scene("unable"); await page.getByRole("button", { name: "展示并重摸", exact: true }).click();
    await page.waitForFunction(() => window.xingbeiDev.exportState().current === 1); await settled();
    const refresh = (await animation()).trace.filter(event => event.status === "started").map(event => event.type);
    check(`${tag}: 重摸先弃牌后摸牌且不扣士气`, refresh.indexOf("discard") < refresh.indexOf("draw") && (await state()).game.teams.red.morale === 15);
    await scene("ending"); await page.locator("#synth").click();
    for (let i = 0; i < 3; i++) await page.locator(".stone-choice").nth(i).click();
    await page.getByRole("button", { name: "确认", exact: true }).click();
    await page.getByRole("button", { name: "再来一局", exact: true }).waitFor();
    check(`${tag}: 第五杯实际结束且有资源反馈`, (await state()).game.winner === "red" && (await animation()).trace.some(event => event.type === "cup"));
    await scene("opening"); await page.locator("#hand .card").first().click(); await page.locator('.player.targetable[data-player="1"]').click();
    await page.waitForFunction(() => window.xingbeiDev.animations().active > 0);
    await page.locator("#dev-reset").click(); await settled();
    check(`${tag}: 动画中重置无串局和残留`, (await state()).game.discard.length === 0 && (await state()).game.players[1].statuses.length === 0 && await page.locator(".animation-layer").count() === 1 && await page.locator(".animation-card").count() === 0);
    await page.locator("#hand .card").first().click(); await page.locator('.player.targetable[data-player="1"]').click();
    await page.waitForFunction(() => window.xingbeiDev.animations().active > 0); await page.setViewportSize({ width: viewport.width + 10, height: viewport.height });
    await page.waitForFunction(() => window.xingbeiDev.exportState().current === 1); await settled();
    check(`${tag}: 缩放结束旧轨迹并保留结算`, await page.locator(".animation-card").count() === 0);
    await scene("opening");
    await page.evaluate(() => window.xingbeiDev.pauseAnimations(true));
    await page.locator("#hand .card").first().click(); await page.locator('.player.targetable[data-player="1"]').click();
    await page.waitForFunction(() => window.xingbeiDev.animations().playing);
    check(`${tag}: 暂停效果停在结算检查点`, (await animation()).active === 0 && (await state()).current === 0);
    await page.evaluate(() => window.xingbeiDev.stepAnimation());
    await page.waitForFunction(() => window.xingbeiDev.animations().trace.some(event => event.type === "move" && event.status === "finished"));
    check(`${tag}: 单步完成一个效果并停在下一检查点`, (await animation()).trace.some(event => event.type === "move" && event.status === "finished"));
    await page.evaluate(() => window.xingbeiDev.pauseAnimations(false));
    await page.waitForFunction(() => window.xingbeiDev.exportState().current === 1); await settled();
    await page.emulateMedia({ reducedMotion: "reduce" }); await scene("purchase");
    const before = Date.now(); await page.locator("#buy").click(); await page.waitForFunction(() => window.xingbeiDev.exportState().current === 1); await settled();
    check(`${tag}: 减少动态效果保持结算并取消等待`, Date.now() - before < 1500 && await page.locator(".animation-card").count() === 0);
    await page.emulateMedia({ reducedMotion: "no-preference" }); await scene("opening");
    await page.locator("#hand .card").first().click(); await page.locator('.player.targetable[data-player="1"]').click();
    await page.waitForFunction(() => window.xingbeiDev.animations().active > 0);
    await page.evaluate(() => { Object.defineProperty(document, "hidden", { configurable: true, get: () => true }); document.dispatchEvent(new Event("visibilitychange")); });
    await page.waitForFunction(() => window.xingbeiDev.exportState().current === 1); await settled();
    check(`${tag}: 后台切换完成动画而不阻塞`, await page.locator(".animation-card").count() === 0);
    await context.close();
  }
  check("无控制台或资源加载错误", issues.length === 0);
} finally {
  await writeFile(resolve(output, "results.json"), JSON.stringify({ checks, issues, traces }, null, 2)); await browser.close();
}
console.log(`通过${checks.length}项动画检查，保存四视口录像与关键帧。`);
